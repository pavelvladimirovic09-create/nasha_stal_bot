def calculate_priority(title: str, summary: str = '') -> int:
    """Priority rules:
    - STOP_WORDS in title or summary -> 0
    - CORE_UA (Ukraine/war): 1+ -> 5
    - CORE_RUSSIA (Russia): 1+ -> 5
    - CORE_WORLD_ME (World/ME): 2+ -> 5, else 0
    - else -> 0
    """
    title_lower = title.lower()
    summary_lower = summary.lower() if summary else ''
    text = f"{title_lower} {summary_lower}"

    for stop in STOP_WORDS:
        if stop in text:
            return 0

    for word in CORE_UA:
        if word in title_lower:
            return 5

    for word in CORE_RUSSIA:
        if word in title_lower:
            return 5

    hits = sum(1 for word in CORE_WORLD_ME if word in title_lower)
    if hits >= 2:
        return 5

    return 0


def sort_news_by_priority(news_list: list) -> list:
    """Сортирует новости по приоритету"""
    scored_news = []
    for item in news_list:
        title = item.get('title', '')
        summary = item.get('summary', '')
        source = item.get('source', '')
        priority = calculate_priority(title, summary)
        
        if priority > 0:
            item['priority'] = priority
            scored_news.append(item)
    
    scored_news.sort(key=lambda x: x.get('priority', 0), reverse=True)
    return scored_news

