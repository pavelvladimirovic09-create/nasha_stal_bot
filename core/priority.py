def calculate_priority(title: str, summary: str, source: str = '') -> int:
    """Рассчитывает приоритет новости"""
    title_lower = title.lower()
    summary_lower = summary.lower() if summary else ''
    
    # 1. Стоп-слова в заголовке ИЛИ summary
    for stop in STOP_WORDS:
        if stop in title_lower or stop in summary_lower:
            return 0
    
    # 2. Важные слова — ТОЛЬКО в заголовке
    for word in IMPORTANT_WORDS:
        if word in title_lower:
            return 5
    
    return 0

def sort_news_by_priority(news_list: list) -> list:
    """Сортирует новости по приоритету"""
    scored_news = []
    for item in news_list:
        title = item.get('title', '')
        summary = item.get('summary', '')
        source = item.get('source', '')
        priority = calculate_priority(title, summary, source)
        
        if priority > 0:
            item['priority'] = priority
            scored_news.append(item)
    
    scored_news.sort(key=lambda x: x.get('priority', 0), reverse=True)
    return scored_news

